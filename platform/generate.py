def probe(p: dict, kind: str) -> dict:
    out = {"httpGet": {"path": p["path"], "port": p["port"]}}
    for src, dst in (("initial_delay", "initialDelaySeconds"),
                     ("period", "periodSeconds"),
                     ("failure_threshold", "failureThreshold")):
        if src in p:
            out[dst] = p[src]
    return out


def gen_k8s(spec: dict) -> dict[str, str]:
    meta, out = spec["meta"], {}
    ns, acct, region = meta["namespace"], meta["account_id"], meta["region"]
    ecr = f"{acct}.dkr.ecr.{region}.amazonaws.com"

    for name, s in spec["services"].items():
        pod = {
            "serviceAccountName": name,
            "containers": [{
                "name": name,
                "image": f"{ecr}/{s['image_repo']}:PLACEHOLDER_TAG",
                "ports": [{"containerPort": s["probes"]["readiness"]["port"]}],
                "resources": {k: {kk: str(vv) for kk, vv in v.items()}
                              for k, v in s["resources"].items()},
                "envFrom": [{"configMapRef": {"name": f"{name}-config"}}],
            }],
        }
        c = pod["containers"][0]
        for kind in ("startup", "readiness", "liveness"):
            if kind in s["probes"]:
                c[f"{kind}Probe"] = probe(s["probes"][kind], kind)
        if s.get("gpu"):
            pod["nodeSelector"] = s["gpu"]["node_selector"]
            pod["tolerations"] = [s["gpu"]["toleration"]]
        if s.get("init_container"):
            ic = spec["init_containers"][s["init_container"]]
            pod["initContainers"] = [{
                "name": s["init_container"],
                "image": f"{ecr}/{ic['image_repo']}:PLACEHOLDER_TAG",
                "resources": {k: {kk: str(vv) for kk, vv in v.items()}
                              for k, v in ic["resources"].items()},
                "envFrom": [{"configMapRef": {"name": f"{name}-config"}}],
                "volumeMounts": [{"name": "model", "mountPath": "/models"}],
            }]
            pod["volumes"] = [{"name": "model", "emptyDir": {"sizeLimit": "20Gi"}}]
            c["volumeMounts"] = [{"name": "model", "mountPath": "/models"}]

        docs = [
            {"apiVersion": "v1", "kind": "ServiceAccount",
             "metadata": {"name": name, "namespace": ns}},
            {"apiVersion": "apps/v1", "kind": "Deployment",
             "metadata": {"name": name, "namespace": ns},
             "spec": {"replicas": s["replicas"]["min"],
                      "selector": {"matchLabels": {"app": name}},
                      "template": {"metadata": {"labels": {"app": name}}, "spec": pod}}},
            {"apiVersion": "v1", "kind": "Service",
             "metadata": {"name": name, "namespace": ns},
             "spec": {"type": "ClusterIP", "selector": {"app": name},
                      "ports": [{"port": s["probes"]["readiness"]["port"],
                                 "targetPort": s["probes"]["readiness"]["port"]}]}},
        ]
        if s.get("hpa"):
            docs.append({
                "apiVersion": "autoscaling/v2", "kind": "HorizontalPodAutoscaler",
                "metadata": {"name": name, "namespace": ns},
                "spec": {"scaleTargetRef": {"apiVersion": "apps/v1",
                                            "kind": "Deployment", "name": name},
                         "minReplicas": s["replicas"]["min"],
                         "maxReplicas": s["replicas"]["max"],
                         "metrics": [{"type": "Resource", "resource": {
                             "name": s["hpa"]["metric"],
                             "target": {"type": "Utilization",
                                        "averageUtilization": s["hpa"]["target_utilization"]}}}]}})
        out[f"{name}.yaml"] = BANNER + yaml.dump_all(docs, sort_keys=False, width=100)
    return out


# --------------------------------------------------------------------------- #
def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if any generated file is missing or stale")
    args = ap.parse_args()

    spec = yaml.safe_load((ROOT / "services.yaml").read_text())
    files = {IAM_DIR / k: v for k, v in gen_iam(spec).items()}
    files |= {K8S_DIR / k: v for k, v in gen_k8s(spec).items()}

    stale = []
    for path, content in files.items():
        if not path.exists() or path.read_text() != content:
            stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)

    if args.check:
        if stale:
            print("STALE — run platform/generate.py and commit:", file=sys.stderr)
            for p in stale:
                print(f"  {p.relative_to(ROOT.parent)}", file=sys.stderr)
            return 1
        print(f"generated output current ({len(files)} files)")
        return 0

    for p in sorted(files):
        print(f"  wrote {p.relative_to(ROOT.parent)}")
    print(f"\n{len(files)} files from services.yaml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
